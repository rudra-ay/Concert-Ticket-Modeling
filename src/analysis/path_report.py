"""Build reports/path_findings.md from the PATH outputs (every number read from reports/path_tables/).

Order: path_panel.py, path_tm_moves.py, path_readiness.py, path_hypotheses.py, then this script.
Run all: .venv/bin/python src/analysis/path_report.py --all
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from analysis.path_common import TABLES, md_table  # noqa: E402
from analysis.targets import ROOT  # noqa: E402

OUT = ROOT / "reports/path_findings.md"
STEPS = ["path_panel.py", "path_tm_moves.py", "path_readiness.py", "path_hypotheses.py"]


def j(name: str) -> dict:
    return json.loads((TABLES / name).read_text())


def n(x) -> str:
    return f"{x:,}" if isinstance(x, int) else f"{x:,.1f}"


def main() -> None:
    if "--all" in sys.argv:
        for s in STEPS:
            subprocess.run([sys.executable, str(Path(__file__).parent / s)], check=True)
    mv, rd, ps, fam = j("tm_moves_summary.json"), j("readiness_summary.json"), j("panel_summary.json"), j("bh_family.json")
    sc = rd["scenarios"]
    A, B, C = (sc[k] for k in ("A status quo (3,000, far 60%)", "B expand to 4,000 (far 60%)",
                               "C expand to 4,000 (far 30%)"))
    qa, qb = A["quota"], B["quota"]
    days = pd.read_csv(TABLES / "tm_moves_days.csv")
    genre = pd.read_csv(TABLES / "tm_moves_genre.csv")
    pool = pd.read_csv(TABLES / "tm_moves_pool.csv")
    trans = pd.read_csv(TABLES / "tm_moves_status_transitions.csv")
    sched = pd.read_csv(TABLES / "readiness_schedule.csv")
    doc = (ROOT / "FORWARD_COLLECTOR.md").read_text()
    code = (ROOT / "forward_collector.py").read_text()
    implemented = "DEFAULT_TARGET = 4000" in code
    documented = "4,000" in doc and "rolling" in doc.lower()

    def cols(t: pd.DataFrame, keys: list[str], names: list[str]) -> str:
        t = t[keys].copy()
        t.columns = names
        return md_table(t)

    L: list[str] = []
    w = L.append
    w("# PATH findings (task 8): what the forward panel shows now, and when it will be ready")
    w("")
    w("Generated by `src/analysis/path_report.py --all` (runs `path_panel.py`, `path_tm_moves.py`, `path_readiness.py`, "
      "`path_hypotheses.py`). Every number below comes from `reports/path_tables/`. The forward panel "
      "(`data/forward/tm_forward.sqlite`) is opened read-only, and only aggregates are written (Ticketmaster storage terms, "
      "FORWARD_COLLECTOR.md §6). \"Data from Ticketmaster Discovery API.\"")
    w("")
    w("> **All prices in this report are PRIMARY-market face values** (Ticketmaster `priceRanges`: "
      f"{', '.join(mv['range_types'])}, without fees). **They are not resale prices.** No resale PATH hypothesis "
      "(late decline, late rise for sell-outs, a T-9/10 peak, final-hours minimum) can be tested from this panel. "
      "Those still wait on the Rebrowser grant or the marketplace permissions.")
    w("")
    w("## Summary")
    w("")
    w(f"- **[P1] Primary face value almost never moves day to day.** Over the {mv['n_snap_days']} snapshot days so far, "
      f"{mv['pairs_moved']} of {n(mv['pairs_both_priced'])} priced event-day pairs changed min or max face value: "
      f"{mv['move_rate_pct']}% (95% CI {mv['move_rate_ci95_pct'][0]}–{mv['move_rate_ci95_pct'][1]}%). "
      f"No event changed its number of price levels ({mv['tiers_changed']} changes). When a change happened it was a step "
      f"(median |Δ| {mv['median_abs_pct_min_change']}% for min, {mv['median_abs_pct_max_change']}% for max). That is consistent with H20 "
      "(tier releases, not drift), but this is descriptive: 2 day-to-day transitions are far too short to test anything.")
    w(f"- **[P2] Readiness** (scenario C, in force from 2026-10-22). N ≥ 200 complete priced paths arrive by "
      f"{C['dates']['h7_N200_priced']} (7-day), {C['dates']['h14_N200_priced']} (14-day), "
      f"{C['dates']['h30_N200_priced']} (30-day) and {C['dates']['h60_N200_priced']} (60-day). N ≥ 1,000 arrives by "
      f"{C['dates']['h7_N1000_priced']}, {C['dates']['h14_N1000_priced']}, {C['dates']['h30_N1000_priced']} and "
      f"{C['dates']['h60_N1000_priced']}. The full table, with the old 3,000 target for comparison, is in P2.")
    w(f"- **[P3] Watchlist raised to 4,000 events, far share 30% (scenario C): implemented by collector-path and chosen "
      f"by the lead.** It is quota-safe: worst day {n(qb['worst_case_day_calls'])} calls against the {n(qb['budget'])} "
      f"rolling-24 h budget. Priced N ≥ 1,000 moves from {A['dates']['h7_N1000_priced']} to {C['dates']['h7_N1000_priced']} "
      f"for 7-day paths, from {A['dates']['h14_N1000_priced']} to {C['dates']['h14_N1000_priced']} for 14-day paths, and "
      f"from {A['dates']['h30_N1000_priced']} to {C['dates']['h30_N1000_priced']} for 30-day paths. 60-day dates are "
      f"unchanged. The trade-off: the 60-day IPW effective sample size is {C['ipw']['h60_by_2027-02-16']['kish_ess']}, "
      f"against {B['ipw']['h60_by_2027-02-16']['kish_ess']} had the far share stayed at 60% (status quo "
      f"{A['ipw']['h60_by_2027-02-16']['kish_ess']})."
      + ("" if implemented and documented else " (FORWARD_COLLECTOR.md update pending.)"))
    w("- **[P4] Literature.** LITERATURE.md §C adds 7 sources and a table of what predicts path shape. Remaining inventory "
      "relative to time and the timing mix of late buyers are the main moderators, and both need resale data.")
    w(f"- **[P5] No clustering of path shapes yet.** The panel has {ps['snap_days']} snapshot days and no complete path of any "
      "horizon. What the collector still needs is listed in P5.")
    w("")

    w("## [P1] What the forward panel shows today (PRIMARY face value)")
    w("")
    w(f"Panel: {n(mv['snapshots_200'])} HTTP-200 snapshots of {n(mv['events'])} events on {', '.join(mv['snap_days'])} "
      f"(UTC run days). {n(mv['snapshots_with_ranges'])} snapshots carry `priceRanges`; "
      f"{n(mv['zero_placeholder_snapshots'])} of those are **$0.00 placeholder ranges**, which are treated as missing, so a "
      "$0 → price step counts as a range appearing, not as repricing. A day-pair is the same event on two consecutive "
      f"days. There are {n(mv['day_pairs'])} day-pairs, {n(mv['pairs_both_priced'])} of them priced on both days. "
      "A *move* is a change of more than half a cent in the min or max face value.")
    w("")
    w(f"- **Move rate:** {mv['pairs_moved']} moves in {n(mv['pairs_both_priced'])} priced day-pairs = **{mv['move_rate_pct']}%** "
      f"(Wilson 95% CI {mv['move_rate_ci95_pct'][0]}–{mv['move_rate_ci95_pct'][1]}%). By event: {mv['events_moved']} of "
      f"{n(mv['events_with_2plus_priced_days'])} events with ≥ 2 priced consecutive days moved at least once "
      f"({mv['event_move_rate_pct']}%, CI {mv['event_move_rate_ci95_pct'][0]}–{mv['event_move_rate_ci95_pct'][1]}%).")
    w(f"- **Direction and size:** {mv['moves_up']} pairs had an upward change and {mv['moves_down']} a downward change "
      "(a pair can have both). Among moves, the median |Δmin| is "
      f"{mv['median_abs_pct_min_change']}% and the median |Δmax| is {mv['median_abs_pct_max_change']}%. These are steps, not small drifts.")
    w(f"- **Price levels:** the number of ranges per event never changed ({mv['tiers_changed']}). Every range is "
      "`standard` USD without fees, so no fee-inclusive type appeared and fee dynamics are invisible here.")
    w(f"- **Ranges appearing or disappearing:** {mv['ranges_appeared']} appeared out of {n(mv['pairs_unpriced_before'])} unpriced-before pairs, "
      f"and {mv['ranges_disappeared']} disappeared. In the random no-ranges draw, no range appeared yet "
      f"({int(pool.loc[pool.pool == 'random no-ranges draw', 'ranges_appeared'].iloc[0])} of "
      f"{n(int(pool.loc[pool.pool == 'random no-ranges draw', 'pairs_unpriced_before'].iloc[0]))} pairs). That is the "
      "promotion and IPW question, and it needs weeks to answer.")
    w(f"- **Status changes:** {mv['status_changes']} day-pairs changed `event_status`. Onsale ↔ offsale flips dominate "
      "(table below). Offsale is not a sell-out flag: the Discovery API has no sell-through, so \"fill\" below means the "
      "selection pool (events chosen because they publish ranges vs. the random no-ranges draw).")
    w("")
    w("**By days to show** (later snapshot of the pair). See also `charts/path_tm_moves_by_daysout.png`.")
    w("")
    w(cols(days, ["bucket", "day_pairs", "pairs_both_priced", "moves", "move_rate_pct", "ci95_lo_pct", "ci95_hi_pct",
                  "ranges_appeared", "status_changes"],
           ["days to show", "day-pairs", "priced pairs", "moves", "move %", "CI lo %", "CI hi %", "ranges appeared",
            "status changes"]))
    w("")
    w("**By genre** (genres with ≥ 100 priced pairs). See also `charts/path_tm_moves_by_genre.png`.")
    w("")
    w(cols(genre, ["genre_g", "pairs_both_priced", "moves", "move_rate_pct", "ci95_lo_pct", "ci95_hi_pct"],
           ["genre", "priced pairs", "moves", "move %", "CI lo %", "CI hi %"]))
    w("")
    w("**By selection pool (\"fill\")**")
    w("")
    w(cols(pool, ["pool", "day_pairs", "pairs_both_priced", "moves", "move_rate_pct", "ranges_appeared", "status_changes"],
           ["pool", "day-pairs", "priced pairs", "moves", "move %", "ranges appeared", "status changes"]))
    w("")
    w("**Status transitions**")
    w("")
    w(cols(trans, ["prev_event_status", "event_status", "n"], ["from", "to", "day-pairs"]))
    w("")
    w("Reading: none of the bucket or genre differences can be distinguished. Every CI overlaps, and the counts of moves "
      "per cell are single digits. These tables are a baseline for the pre-registered tests (H20a/H20b/H9p/H37 below), "
      "not evidence for them.")
    w("")
    w("![Primary face value: daily move rate by days to show](charts/path_tm_moves_by_daysout.png)")
    w("")
    w("![Primary face value: daily move rate by genre](charts/path_tm_moves_by_genre.png)")
    w("")

    w("## [P2] Data-readiness schedule")
    w("")
    w("A **complete h-day path** has daily snapshots from h days before the show through show day. The event must be "
      "first snapshotted ≥ h days out, with at most ⌊0.1·(h+1)⌋ missing days, which allows "
      f"{rd['allowed_misses']['7']}, {rd['allowed_misses']['14']}, {rd['allowed_misses']['30']} and "
      f"{rd['allowed_misses']['60']} misses for h = 7, 14, 30 and 60. A path counts as **priced** if it also has a valid "
      "range (min > 0): for events already watched, the latest snapshot; for future additions, the candidate's flag "
      f"discounted by the observed {rd['placeholder_share']} share of $0 placeholders. Counts are **expected values**: each "
      "event contributes P(complete), with days already missed counted exactly and future days missing at the observed "
      f"per-event rate of {rd['p_miss_per_event_day']}.")
    w("")
    w(f"Future additions are simulated with the collector's own selection code (`forward_collector.select_panel`, option (b)) "
      f"day by day from 2026-10-22, topping the watchlist up to its target from the {n(rd['candidates_not_on_watchlist'])} "
      f"known candidates. New day-120 slices are added at the observed rate of {rd['arrivals_per_day']} events per day, "
      f"resampled from the 90–120-day mix of the first full scan ({rd['arrival_template_ranges_share']} with ranges). "
      "Without these arrivals (rows A0/B0 in `readiness_schedule.csv`) the 7- to 30-day dates hardly change, but N ≥ 1,000 "
      "priced 60-day paths is never reached by 2027-06-30. The far band's priced pool was exhausted on day 1, so the "
      "60-day horizon depends on new far events publishing ranges.")
    w("")
    w("**First date by which N complete paths exist.** The status quo is the old target of 3,000 with a 60% far share. "
      "**The 4,000 / far 30% columns (scenario C) are the configuration in force from 2026-10-22.**")
    w("")
    wide = sched[sched.scenario.isin(["A status quo (3,000, far 60%)", "B expand to 4,000 (far 60%)",
                                      "C expand to 4,000 (far 30%)"])].copy()
    wide["col"] = wide.scenario.str[0] + " " + wide.paths
    t = wide.pivot_table(index=["horizon_days", "N"], columns="col", values="date", aggfunc="first").reset_index()
    t = t[["horizon_days", "N", "A all", "A priced", "B all", "B priced", "C all", "C priced"]]
    t.columns = ["horizon (days)", "N", "status quo: all", "status quo: priced", "4,000 far 60%: all",
                 "4,000 far 60%: priced", "C, in force: all", "C, in force: priced"]
    w(md_table(t).replace("\n", "\n"))
    w("")
    w(f"- **Short horizons arrive well before 2026-12-18**, as expected. Under C, priced N ≥ 200 is reached on "
      f"{C['dates']['h7_N200_priced']} (7-day) and {C['dates']['h14_N200_priced']} (14-day), and N ≥ 500 on "
      f"{C['dates']['h7_N500_priced']} and {C['dates']['h14_N500_priced']} (old target: "
      f"{A['dates']['h7_N500_priced']} and {A['dates']['h14_N500_priced']}).")
    w(f"- **The 60-day horizon is set by the calendar, not by slots.** The first complete 60-day paths can only finish 60 days "
      f"after collection began, and priced N ≥ 1,000 arrives on {A['dates']['h60_N1000_priced']} in every scenario.")
    w(f"- **Whole-day outages are the main risk for short horizons.** The per-event miss rate excludes days the Mac is off "
      f"all day. One such day in November would end about {rd['outage_one_day_h7_paths_lost_nov_mean']} in-progress 7-day "
      f"paths ({rd['outage_one_day_h7_priced_paths_lost_nov_mean']} priced; current watchlist, average over November days). "
      "A 14-day path tolerates one such day, and 30- and 60-day paths tolerate three and six. On 2026-10-20 the "
      "scheduled run was cut by the quota, and a second run the same day took the missing snapshots.")
    w("")
    w("![Readiness](charts/path_readiness.png)")
    w("")

    w("## [P3] Watchlist expansion: quota math, effect on dates and IPW")
    w("")
    w("Quota (all values from `readiness_summary.json`; budget 4,500 calls per 24 h, Ticketmaster quota 5,000):")
    w("")
    qt = pd.DataFrame([{"target": n(q["target"]), "worst day (calls)": n(q["worst_case_day_calls"]),
                        "headroom": n(q["headroom"]), "est. run time (min, observed rate)": q["est_run_minutes_observed_rate"],
                        "2nd run <24 h later: calls available": n(q["back_to_back_second_run_calls_available"])}
                       for q in (qa, qb)])
    w(md_table(qt))
    w("")
    w(f"- Worst day = target × (1 + {qb['retry_margin_pct']}% retry/error margin; observed max {qb['observed_overhead_max_pct']}%) "
      f"+ {qb['rescan_reserve']} reserved for the weekly full discover rescan (observed {qb['observed_full_rescan_calls']} calls, "
      f"pilot included). The largest safe target is {n(qb['max_safe_target'])}. 4,000 leaves {qb['headroom']} calls of headroom, "
      "and Ticketmaster's Rate-Limit-Available stays above the collector's 250-call stop.")
    w(f"- **The quota is a rolling 24 h window** (collector-path found this on 2026-10-21: on 2026-10-20 the quota ran low "
      f"after {n(rd['first_budget_stop_calls'])} calls because the previous run still counted). With one run per day this is fine. If a catch-up run "
      f"(Mac asleep at 09:15) lands less than 24 h before the next scheduled run, the second run has only "
      f"{qb['back_to_back_second_run_calls_available']} calls until the first run's calls age out. It waits up to 3 h, then "
      "stops. Snapshots go nearest show first, so the far events lose that day; a 60-day path tolerates six such misses.")
    w(f"- Run time uses the observed throughput of the largest daily run ({qb['observed_calls_per_min']} calls/min; the run is "
      "latency-bound, well under the 3 req/s cap), so a 4,000-event day takes about two hours.")
    w(f"- **What changed in selection:** only the target (4,000) and the far share (30% of new slots, was 60%). Option (b), "
      f"the 80% ranges pool and per-pick `selection_prob` are unchanged. The first top-up is the 2026-10-22 daily run "
      f"(simulated: about {C['added_by_2026_10_22']:,} events that day). FORWARD_COLLECTOR.md documents the change, the "
      "drift risk, and the IPW rule below.")
    w("")
    w("**Effect on IPW** (Kish effective sample size of 1/selection_prob weights among expected complete paths by the "
      "milestone date; pilot events carry no weights and are excluded):")
    w("")
    ipw = []
    for lab, s in (("status quo 3,000", A), ("4,000 far 60%", B), ("4,000 far 30%", C)):
        for k, v in s["ipw"].items():
            ipw.append({"scenario": lab, "paths by": k, "expected paths": n(v["n_expected"]), "Kish ESS": v["kish_ess"],
                        "weight CV": v["weight_cv"]})
    w(md_table(pd.DataFrame(ipw)))
    w("")
    w("Weights are very uneven (CV above 2): the random no-ranges draw has small selection probabilities and large "
      "weights. Both expansions lower the CV. The 30% far share (C, implemented) gives the largest ESS at 7 to 30 days "
      "but gives back most of the 60-day gain that a 60% far share would have had. **Caveat on these ESS figures:** they "
      "pool all selection days. `selection_prob` is the share within that day's pool, and the band mix changed between "
      "cohorts (60% far on 2026-10-19, 30% from 2026-10-22). So the analysis must treat the selection day as an extra "
      "stratum and combine cohort-stratified estimates (FORWARD_COLLECTOR.md). Pooled ESS is a rough guide to "
      "relative precision only.")
    w("")
    w("## [P4] Literature on PATH (LITERATURE.md §C)")
    w("")
    w("New verified sources: Gallego & van Ryzin (1994), Board & Skrzypacz (2016), Williams (2022), Xu, Fader & "
      "Veeraraghavan (2019), Diehl, Maxcy & Drayer (2015), Waisman (2017 seminar abstract) and Kemper & Breuer (2016), "
      "each with a verification marker. On top of the existing Sweeting (2012), Leslie & Sorensen (2014), Courty (2003), "
      "Bhave & Budish (2023) and CMA (2025) entries, the literature names these predictors of path shape: "
      "**remaining inventory relative to time** (sell-out status), **the timing mix of buyers** (late high-value demand), "
      "**seller type**, **seat tier**, **the primary pricing regime** and **late demand news**. All but the primary regime "
      "need resale data. Two new hypotheses: H36 (resale paths differ by seat tier; excluded until resale data exist) and "
      "H37 (primary face changes cluster at scheduled sale-phase dates; in the family).")
    w("")

    w("## [P5] Path-shape clustering: not supported yet")
    w("")
    w(f"Clustering needs complete paths, and none exist: {ps['snap_days']} snapshot days, {n(ps['panel_events'])} events, "
      f"{n(ps['panel_rows'])} panel rows. Clustering would also be nearly empty of signal on primary face values, which "
      f"moved on {mv['move_rate_pct']}% of priced day-pairs. What the collector still needs:")
    w("")
    w(f"1. **≥ 500 complete priced 30-day paths** (expected {C['dates']['h30_N500_priced']} under C; "
      f"{A['dates']['h30_N500_priced']} under the old target) for primary-path summaries, and ≥ 1,000 "
      f"({C['dates']['h30_N1000_priced']}) for moderator splits.")
    w("2. **Daily continuity.** Whole-day outages break short paths (P2), so the Mac must be awake at 09:15 or the job must catch up the same day.")
    w("3. **Resale data for resale shapes.** Shapes like a late decline, a late rise or a mid-path peak are resale "
      "phenomena. Primary face paths will mostly be flat with occasional steps, so the useful primary features are "
      "step count, step timing relative to sale phases (H37) and range spread.")
    w("4. **A registered design before any fit:** shape features (normalized path on a 0–60-day grid, number and timing "
      "of steps, net change), k chosen by silhouette on the training artists, and a split time-ordered and grouped by "
      "artist. These go into `path_spec.json` (currently no features and no split, because no model is fitted and no "
      "out-of-sample claim is made). <!-- notrace: design constants -->")
    w("")

    w("## Pre-registered PATH hypotheses (BH family, declared 2026-10-21)")
    w("")
    w("The family is fixed now, before any estimate exists. Every member is **pending** and enters BH at p = 1 until its "
      "test date. " + fam["common"] + " <!-- notrace: design constants (thresholds, draws, cluster rule) -->")
    w("")
    ft = pd.DataFrame([{"hid": h, "claim": d["claim"], "test": d["test"], "status": "pending (p = 1, q = 1)"}
                       for h, d in fam["definitions"].items()])
    w(md_table(ft) + " <!-- notrace: pre-registration text -->")
    w("")
    w("Test date for every member: " + fam["pending_p1"][fam["family"][0]].split("until: ")[1]
      + ". Disclosure: " + fam["disclosure"] + ".")
    w("")
    resale = [k for k, v in fam["excluded"].items() if v.startswith("resale-price hypothesis")]
    other = {k: v for k, v in fam["excluded"].items() if k not in resale}
    w("**Excluded with reasons.** Resale-price hypotheses (the panel is PRIMARY face value; they need the Rebrowser "
      "StubHub/Gametime data or marketplace permissions): " + ", ".join(resale) + ". Others: "
      + "; ".join(f"{k}: {v}" for k, v in other.items()) + ". The full reasons are in `bh_family.json`.")
    w("")
    w("No out-of-sample claim is made in this report, so there is no final spec and no test-split touch.")
    w("")
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(L)} lines); implemented={implemented} documented={documented}")


if __name__ == "__main__":
    main()
